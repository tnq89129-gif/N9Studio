using Backend.Contracts;
using Backend.Controllers;
using Backend.Data;
using Backend.Models;
using Backend.Services;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using System.Security.Claims;
using Microsoft.AspNetCore.Http;
static void Check(bool value,string message){if(!value)throw new Exception(message);}
await using var connection=new SqliteConnection("Data Source=:memory:");await connection.OpenAsync();
var options=new DbContextOptionsBuilder<ShopDbContext>().UseSqlite(connection).Options;
await using var db=new ShopDbContext(options);await db.Database.EnsureCreatedAsync();
var c=new CategoriesController(db);
Check(await c.Create(new CategoryRequest("   ")) is BadRequestObjectResult,"Whitespace name rejected");
Check(await c.Create(new CategoryRequest("Áo thun","bad/code")) is BadRequestObjectResult,"Invalid code rejected");
Check(await c.Create(new CategoryRequest("  Áo   thun  ","ao-thun","Cotton")) is OkObjectResult,"Create category");
var cat=await db.Categories.SingleAsync();Check(cat.Name=="Áo thun"&&cat.Code=="ao-thun","Name normalization");
Check(await c.Create(new CategoryRequest("Áo thun","other")) is ConflictObjectResult,"Duplicate name");
Check(await c.Create(new CategoryRequest("Other","ao-thun")) is ConflictObjectResult,"Duplicate code");
Check(await c.Update(cat.Id,new CategoryRequest("Áo đẹp","ao-dep","New")) is NoContentResult,"Update category");
var product=new Product{Name="Test",CategoryId=cat.Id,Variants=[new ProductVariant{Size="M",Color="Đen",Price=100,Stock=3}]};db.Products.Add(product);await db.SaveChangesAsync();
Check(await c.Update(cat.Id,new CategoryRequest("Áo đẹp","changed")) is ConflictObjectResult,"Do not rename in-use code");
Check(await c.Delete(cat.Id) is ConflictObjectResult,"Do not delete populated category");
var catalog=new CatalogController(db);
Check(await catalog.Detail(product.Id) is OkObjectResult,"Initially visible");
Check(await c.Status(cat.Id,new CategoryStatusRequest(false)) is NoContentResult,"Hide category");
db.ChangeTracker.Clear();
Check(await catalog.Detail(product.Id) is NotFoundResult,"Hidden category not accessible by direct product id");
var cats=(OkObjectResult)await catalog.Categories();
Check(((List<Category>)cats.Value!).Count==0,"Hidden category absent from public filters");
var user=new ShopUser{Id="user-1",UserName="test@example.com",Email="test@example.com"};db.Users.Add(user);await db.SaveChangesAsync();
var controllerContext=new ControllerContext{HttpContext=new DefaultHttpContext{User=new ClaimsPrincipal(new ClaimsIdentity([new Claim(ClaimTypes.NameIdentifier,user.Id)],"test"))}};
var cart=new CartController(db){ControllerContext=controllerContext};
Check(await cart.Add(new CartRequest(product.Variants[0].Id,1)) is NotFoundResult,"Cannot buy hidden category through direct variant id");
db.CartItems.Add(new CartItem{UserId=user.Id,VariantId=product.Variants[0].Id,Quantity=1});await db.SaveChangesAsync();
var orders=new OrdersController(db){ControllerContext=controllerContext};
Check(await orders.Checkout(new CheckoutRequest("Test","0901234567","Address")) is ConflictObjectResult,"Existing cart cannot checkout hidden category");
Check(await db.Orders.CountAsync()==0,"No order created after blocked checkout");
Check((await db.Variants.AsNoTracking().SingleAsync()).Stock==3,"No stock lost after blocked checkout");
Check(await c.Status(cat.Id,new CategoryStatusRequest(true)) is NoContentResult,"Show category again");
db.ChangeTracker.Clear();Check(await catalog.Detail(product.Id) is OkObjectResult,"Product visible again");
Check(await c.Create(new CategoryRequest("Trống")) is OkObjectResult,"Old name-only API remains supported");
var empty=await db.Categories.SingleAsync(x=>x.Name=="Trống");Check(CategoryRules.ValidCode(empty.Code),"Auto-generate a valid code");
Check(await c.Delete(empty.Id) is NoContentResult,"Delete empty category");
Check(await c.Detail(empty.Id) is NotFoundResult,"Deleted category is missing");
Console.WriteLine("PASS relational category CRUD/normalization/duplicates, hide/show, catalog visibility, direct cart and checkout guards, empty-only deletion. SQLite used; SQL Server upgrade script is not executed by this test.");
